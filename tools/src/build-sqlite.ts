// Builds dist/coffee.sqlite and copies it into the mobile app's assets.
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import initSqlJs from 'sql.js';
import { DIST_DIR, ROOT, loadDataset } from './lib/load.ts';
import { buildTables } from './lib/rows.ts';
import { readMigrations, seedSql } from './lib/sql.ts';

export async function buildSqlite(): Promise<Uint8Array> {
  const SQL = await initSqlJs();
  const db = new SQL.Database();
  db.run('PRAGMA foreign_keys = ON;');
  db.run(readMigrations());
  db.run('BEGIN;');
  db.run(seedSql(buildTables(loadDataset())));
  db.run('COMMIT;');
  const broken = db.exec('PRAGMA foreign_key_check;');
  if (broken.length > 0) throw new Error('SQLite foreign key check failed');
  db.run('VACUUM;');
  const bytes = db.export();
  db.close();
  return bytes;
}

if (process.argv[1]?.endsWith('build-sqlite.ts')) {
  const bytes = await buildSqlite();
  mkdirSync(DIST_DIR, { recursive: true });
  const out = join(DIST_DIR, 'coffee.sqlite');
  writeFileSync(out, bytes);
  console.log(`✓ wrote dist/coffee.sqlite (${(bytes.length / 1024).toFixed(0)} KB)`);

  const appAssets = join(ROOT, 'apps/mobile/assets/data');
  if (existsSync(join(ROOT, 'apps/mobile'))) {
    mkdirSync(appAssets, { recursive: true });
    copyFileSync(out, join(appAssets, 'coffee.db'));
    // The app names its on-device copy after this fingerprint, so a new build
    // gets a fresh copy and an unchanged one is never copied over itself.
    const version = createHash('sha256').update(bytes).digest('hex').slice(0, 12);
    writeFileSync(
      join(ROOT, 'apps/mobile/src/db-version.ts'),
      `// Generated by npm run build:sqlite. Do not edit.
export const DATABASE_VERSION = '${version}';
`,
    );
    console.log(`✓ copied to apps/mobile/assets/data/coffee.db (version ${version})`);
  }
}
